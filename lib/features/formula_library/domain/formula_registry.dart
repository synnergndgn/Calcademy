abstract final class FormulaRegistry {
  static final List<FormulaEntry> entries = List.unmodifiable(_entries);
  static final Map<String, FormulaEntry> _byId = {
    for (final entry in entries) entry.id: entry,
  };

  static FormulaEntry? byId(String id) => _byId[id];

  static List<FormulaEntry> search({
    String query = '',
    FormulaCategory? category,
    String languageCode = 'en',
  }) {
    final needle = query.trim().toLowerCase();
    return entries
        .where((entry) {
          if (category != null && entry.category != category) return false;
          if (needle.isEmpty) return true;
          final haystack = [
            entry.titleEn,
            entry.titleTr,
            entry.descriptionEn,
            entry.descriptionTr,
            entry.plainTextFormula,
            entry.category.titleEn,
            entry.category.titleTr,
            ...entry.tags,
            ...entry.variables.expand(
              (item) => [item.symbol, item.nameEn, item.nameTr],
            ),
          ].join(' ').toLowerCase();
          return haystack.contains(needle);
        })
        .toList(growable: false);
  }
}

