FormulaEntry _f(
  String id,
  String titleEn,
  String titleTr,
  FormulaCategory category,
  String formula,
  String descriptionEn,
  String descriptionTr,
  List<String> variableSpecs,
  String given,
  String result,
  String toolId,
  String tags, {
  FormulaDifficulty difficulty = FormulaDifficulty.basic,
}) {
  final tool = CalcademyToolRegistry.byId(toolId)!;
  final variables = variableSpecs
      .map((spec) {
        final parts = spec.split('|');
        return FormulaVariable(
          symbol: parts[0],
          nameEn: parts[1],
          nameTr: parts[2],
          descriptionEn: 'Represents ${parts[1]} in this formula.',
          descriptionTr: 'Bu formülde ${parts[2]} değerini temsil eder.',
        );
      })
      .toList(growable: false);
  return FormulaEntry(
    id: id,
    titleEn: titleEn,
    titleTr: titleTr,
    category: category,
    formulaText: formula,
    plainTextFormula: formula,
    descriptionEn: descriptionEn,
    descriptionTr: descriptionTr,
    variables: variables,
    examples: [
      FormulaExample(
        titleEn: 'Worked example',
        titleTr: 'Çözümlü örnek',
        givenValues: {'given': given},
        stepsEn: [
          'Substitute the given values into the formula.',
          'Simplify the expression carefully.',
        ],
        stepsTr: [
          'Verilen değerleri formülde yerine koyun.',
          'İfadeyi dikkatlice sadeleştirin.',
        ],
        result: result,
      ),
    ],
    tags: tags.split(','),
    relatedTools: [
      FormulaToolLink(
        toolId: tool.id,
        route: tool.route,
        labelEn: 'Open in ${tool.titleEn}',
        labelTr: '${tool.titleTr} aracında aç',
        supportedPrefill: tool.supportsPrefill,
        prefillSchema: tool.inputSchema,
      ),
    ],
    difficulty: difficulty,
  );
}
